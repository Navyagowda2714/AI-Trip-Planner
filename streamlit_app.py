"""Streamlit front-end for the AI Trip Planner.

Two modes:
* Standalone (default, used for the hosted demo): the LangGraph agent runs inside
  this Streamlit process. API keys are read from Streamlit secrets or environment.
* Client mode: set BACKEND_URL (e.g. http://localhost:8000) to send questions to
  the FastAPI backend in main.py instead.
"""
import datetime
import os

import requests
import streamlit as st

API_KEYS = [
    "GROQ_API_KEY", "OPENAI_API_KEY", "TAVILY_API_KEY", "GPLACES_API_KEY",
    "OPENWEATHERMAP_API_KEY", "EXCHANGE_RATE_API_KEY",
]


def load_secrets_into_env() -> None:
    """Copy Streamlit Cloud secrets into env vars, where the tools expect them."""
    try:
        for key in API_KEYS + ["BACKEND_URL", "MODEL_PROVIDER"]:
            if key in st.secrets and not os.getenv(key):
                os.environ[key] = str(st.secrets[key])
    except Exception:  # no secrets.toml locally — fine, fall back to .env / env vars
        pass


def ask_backend(question: str, backend_url: str) -> str:
    response = requests.post(f"{backend_url.rstrip('/')}/query", json={"question": question}, timeout=300)
    response.raise_for_status()
    return response.json().get("answer", "No answer returned.")


@st.cache_resource(show_spinner=False)
def get_agent(provider: str):
    from agent.agentic_workflow import GraphBuilder

    return GraphBuilder(model_provider=provider)()


def ask_agent(question: str, provider: str) -> str:
    output = get_agent(provider).invoke({"messages": [question]})
    if isinstance(output, dict) and "messages" in output:
        return output["messages"][-1].content
    return str(output)


def format_plan(answer: str) -> str:
    generated = datetime.datetime.now().strftime("%Y-%m-%d at %H:%M")
    return (
        f"# 🌍 AI Travel Plan\n\n**Generated:** {generated}\n\n---\n\n{answer}\n\n---\n\n"
        "*This travel plan was generated by AI. Please verify prices, opening hours and "
        "travel requirements before your trip.*"
    )


def main() -> None:
    st.set_page_config(page_title="AI Trip Planner", page_icon="🌍", layout="centered")
    load_secrets_into_env()

    backend_url = os.getenv("BACKEND_URL", "").strip()
    provider = os.getenv("MODEL_PROVIDER", "groq")

    st.title("🌍 AI Trip Planner")
    st.caption("LangGraph agent with live weather, places, currency and cost tools.")

    missing = [k for k in ("GROQ_API_KEY" if provider == "groq" else "OPENAI_API_KEY",) if not os.getenv(k)]
    if not backend_url and missing:
        st.warning(f"Missing API key: {', '.join(missing)}. Add it to `.env` or Streamlit secrets.")

    with st.form(key="query_form", clear_on_submit=False):
        user_input = st.text_input("Where do you want to go?", placeholder="e.g. Plan a 5-day trip to Goa on a ₹40,000 budget")
        submitted = st.form_submit_button("Plan my trip")

    if submitted and user_input.strip():
        with st.spinner("Planning your trip — calling weather, places and currency tools..."):
            try:
                answer = ask_backend(user_input, backend_url) if backend_url else ask_agent(user_input, provider)
            except Exception as exc:  # show the error in the UI instead of crashing
                st.error(f"Could not generate a plan: {exc}")
                return
        plan = format_plan(answer)
        st.markdown(plan)
        st.download_button("Download plan (.md)", plan, file_name="trip_plan.md", mime="text/markdown")


if __name__ == "__main__":
    main()
